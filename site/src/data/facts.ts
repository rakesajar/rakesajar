import type { Fact, Signal, SourceRef } from './types';

const SEED_DATE = '2026-11-21';

type SeedInput = Omit<Fact, 'passage' | 'verifiedAt' | 'verification' | 'kind' | 'status' | 'volatility'> &
  Partial<Pick<Fact, 'kind' | 'status' | 'volatility'>>;

function seed(f: SeedInput): Fact {
  return {
    kind: 'rule',
    status: 'in_force',
    volatility: 'standard',
    ...f,
    passage: null,
    verifiedAt: SEED_DATE,
    verification: 'seed',
  };
}

